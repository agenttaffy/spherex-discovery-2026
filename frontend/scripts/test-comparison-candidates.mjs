import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/services/comparisonCandidates.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const { comparisonCandidates } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const anchor = { id: 'anchor', obs_id: 'a', detector: 'D6', mjd: 60000 };
const others = Array.from({ length: 30 }, (_, i) => ({ id: `id${i}`, obs_id: `obs${i}`, detector: 'D6', mjd: 60001 + i }));
const rows = [anchor, { ...anchor, id: 'duplicate-anchor' }, { id: 'wrong', obs_id: 'wrong', detector: 'D1', mjd: 1 },
  ...others.slice().reverse(), { ...others[4], id: 'duplicate' }];
const selected = comparisonCandidates(rows, anchor);
assert.equal(selected.length, 12);
assert.equal(selected[0].obs_id, 'obs0');
assert.equal(selected.at(-1).obs_id, 'obs29');
assert.equal(new Set(selected.map(row => row.obs_id)).size, 12);
assert.ok(selected.every(row => row.detector === 'D6' && row.obs_id !== 'a'));
assert.deepEqual(comparisonCandidates(rows.slice().reverse(), anchor).map(row => row.id), selected.map(row => row.id));
assert.equal(comparisonCandidates(rows, anchor, 1).length, 1);
assert.equal(comparisonCandidates(rows, anchor, 0).length, 0);
const preferred = comparisonCandidates(rows, anchor, 12, 'id17');
assert.equal(preferred.length, 12);
assert.equal(preferred[0].id, 'id17');
assert.equal(new Set(preferred.map(row => row.obs_id)).size, 12);
assert.equal(comparisonCandidates(rows, anchor, 1, 'id17')[0].id, 'id17');
assert.equal(comparisonCandidates(rows, anchor, 12, 'wrong').some(row => row.id === 'wrong'), false);
